/*
 * ssd1306 — SSD1306 OLED driver via shared I2C bus.
 *
 * Wire protocol: each I2C transaction is [control byte][data bytes].
 *   control 0x00 = next bytes are commands
 *   control 0x40 = next bytes are display RAM data
 *
 * The init sequence below matches Adafruit's reference. After init,
 * GDDRAM is page-addressed (auto-increment column within page, then
 * wrap to next page). ssd1306_set_pos() resets the cursor.
 */

